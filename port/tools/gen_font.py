def glyph_rows(code):
    """8 bytes, bit 7 = leftmost column. Row 0 is the top of the cell."""
    key = code if code in G else chr(code)
    pic = G.get(key)
    if pic is None:
        return [0] * 8
    out = [0]
    for row in pic:
        bits = 0
        for x, c in enumerate(row):
            if c != '.':
                bits |= 0x80 >> x
        out.append(bits)
    return out[:8]


def preview(text):
    for ch in text:
        rows = glyph_rows(ord(ch))
        print("%r" % ch)
        for b in rows:
            print("".join('#' if b & (0x80 >> x) else '.' for x in range(8)))
        print()


def emit(path):
    lines = ["/* Generated by port/tools/gen_font.py -- do not edit by hand.",
             " * 128 glyphs of 8x8, one byte per row, bit 7 = leftmost pixel.",
             " * Drawn as 5x7 pictures inside the cell; the advance is 6 pixels. */",
             "#ifndef SBK_UI_FONT_H",
             "#define SBK_UI_FONT_H",
             "",
             "#define SBK_FONT_CELL 8",
             "#define SBK_FONT_ADVANCE 6",
             "",
             "static const unsigned char sbk_ui_font[128][8] = {"]
    for code in range(128):
        rows = glyph_rows(code)
        name = chr(code) if 32 < code < 127 and chr(code) not in "\\'" else ""
        lines.append("    { %s }, /* %3d %s */" % (", ".join("0x%02X" % b for b in rows), code, name))
    lines += ["};", "", "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % path)


